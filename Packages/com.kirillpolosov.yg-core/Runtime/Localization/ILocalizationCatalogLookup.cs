namespace YgCore.Localization
{
    /// <summary>
    /// Необязательное расширение каталога: строгий поиск шаблона строки на ровно одном языке,
    /// без запасного языка и без возврата ключа. Составной каталог (<see cref="CompositeLocalizationCatalog"/>)
    /// по нему отличает «строки нет в этом каталоге» от «есть запасной вариант»: иначе каталог игры,
    /// у которого нет русской строки, перебил бы русскую строку каталога оболочки своим английским запасным.
    /// </summary>
    public interface ILocalizationCatalogLookup
    {
        /// <summary>
        /// Возвращает шаблон строки (без подстановки аргументов) на указанном языке.
        /// Язык уже нормализован. Если строки на этом языке нет, возвращает false.
        /// </summary>
        bool TryGetTemplate(string language, string key, out string template);
    }
}
