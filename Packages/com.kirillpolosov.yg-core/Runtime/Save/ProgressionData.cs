using System;

namespace YgCore.Save
{
    /// <summary>
    /// Основа данных прогресса любой игры: три поля «конверта», по которым определяется формат,
    /// версия схемы и порядок записей. Игра наследует этот класс и добавляет свои поля.
    ///
    /// Классы-наследники должны быть помечены [Serializable] и содержать только то, что понимает
    /// <c>UnityEngine.JsonUtility</c> (публичные поля, списки, вложенные [Serializable]-классы).
    /// Поля конверта заполняет и проверяет пакет, игре менять их вручную не нужно.
    /// </summary>
    [Serializable]
    public abstract class ProgressionData
    {
        /// <summary>Идентификатор формата игры (задаёт схема). По нему отличают чужие и повреждённые данные.</summary>
        public string format;

        /// <summary>Версия схемы данных. При изменении формата поднимается, а для старых версий пишется миграция.</summary>
        public int schemaVersion;

        /// <summary>Порядковый номер записи. Растёт с каждым сохранением и нужен при слиянии гостя с облаком.</summary>
        public long revision;
    }
}
