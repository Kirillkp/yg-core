namespace YgCore.Save
{
    /// <summary>
    /// Итог последней загрузки прогресса. Числовые значения не менять.
    /// Состояния Corrupted, UnsupportedVersion, PlatformUnavailable и Error блокируют автоматическую запись:
    /// прогресс, который не удалось прочитать, нельзя затирать пустым.
    /// </summary>
    public enum ProgressionLoadState
    {
        /// <summary>Загрузка ещё не выполнялась.</summary>
        NotLoaded = 0,

        /// <summary>Сохранения нет (новый игрок). Запись разрешена.</summary>
        Empty = 1,

        /// <summary>Сохранение прочитано в текущей схеме.</summary>
        Loaded = 2,

        /// <summary>Сохранение прочитано из старой схемы и приведено к текущей (после этого оно сразу записывается заново).</summary>
        Migrated = 3,

        /// <summary>Сохранение повреждено или не наше. Запись заблокирована.</summary>
        Corrupted = 4,

        /// <summary>Сохранение создано более новой версией игры. Запись заблокирована.</summary>
        UnsupportedVersion = 5,

        /// <summary>Хранилища нет (платформа недоступна). Прогресс живёт только в сессии, запись заблокирована.</summary>
        PlatformUnavailable = 6,

        /// <summary>Хранилище вернуло ошибку. Это не значит, что сохранения нет, поэтому запись заблокирована.</summary>
        Error = 7
    }
}
