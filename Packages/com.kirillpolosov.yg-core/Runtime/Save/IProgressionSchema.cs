namespace YgCore.Save
{
    /// <summary>
    /// Описание данных прогресса конкретной игры: идентификатор формата, версия схемы и правила
    /// приведения, слияния и миграции. Пакет умеет читать, писать и сливать данные, а что именно
    /// считать допустимым значением и как объединять поля, знает только игра.
    /// </summary>
    /// <typeparam name="TData">Класс данных игры, наследник <see cref="ProgressionData"/>.</typeparam>
    public interface IProgressionSchema<TData> where TData : ProgressionData, new()
    {
        /// <summary>Идентификатор формата, например «my-game-progress». После выпуска игры не менять.</summary>
        string FormatId { get; }

        /// <summary>Текущая версия схемы. Поднимается при любом изменении формата.</summary>
        int CurrentSchemaVersion { get; }

        /// <summary>
        /// Приводит данные к допустимому виду: отрицательные числа к нулю, списки без повторов и null, значения в диапазоны.
        /// Вызывается при чтении, перед записью и перед слиянием. Получает непустой объект и возвращает его же или новый.
        /// Поля конверта (format, schemaVersion, revision) заполняет пакет после этого вызова.
        /// </summary>
        TData Normalize(TData data);

        /// <summary>
        /// Объединяет прогресс гостя (то, что игрок накопил до входа) с облачным прогрессом после входа.
        /// Оба аргумента уже приведены через <see cref="Normalize"/>. Типичные правила: числа берём большие,
        /// списки объединяем, настройки берём из более свежей записи (по <see cref="ProgressionData.revision"/>).
        /// Номер записи результата пакет устанавливает сам.
        /// </summary>
        TData Merge(TData guest, TData cloud);

        /// <summary>
        /// Читает данные старой схемы (версия строго меньше текущей, но не отрицательная) и возвращает их в текущей.
        /// Если версию прочитать нельзя, бросьте исключение: пакет посчитает сохранение повреждённым и заблокирует запись.
        /// </summary>
        /// <param name="schemaVersion">Версия схемы, записанная в данных.</param>
        /// <param name="payload">Исходная строка JSON.</param>
        TData Migrate(int schemaVersion, string payload);
    }
}
