namespace YgCore.Store
{
    /// <summary>Тип товара. Определяет, что магазин делает после покупки.</summary>
    public enum StoreItemKind
    {
        /// <summary>
        /// Экипируемый предмет (скин, шапка). Покупается один раз и остаётся навсегда, его можно надеть в свою категорию.
        /// Покупка за реальные деньги не «гасится» на платформе.
        /// </summary>
        Equippable = 0,

        /// <summary>
        /// Пакет внутриигровой валюты. Покупается за реальные деньги много раз: после покупки на баланс
        /// зачисляется <see cref="StoreItemDefinition.GrantedCoins"/>, и только после записи прогресса покупка гасится на платформе.
        /// </summary>
        CurrencyPack = 1,

        /// <summary>
        /// Разовая разблокировка без экипировки (например, отключение рекламы). Покупается один раз,
        /// запоминается как «куплено», на платформе не гасится.
        /// </summary>
        Unlock = 2
    }
}
