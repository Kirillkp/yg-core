namespace YgCore.Core
{
    /// <summary>
    /// Крупные состояния приложения. В каждый момент активно ровно одно.
    /// Числовые значения используются в сохранениях и логах, менять их нельзя.
    /// </summary>
    public enum AppState
    {
        /// <summary>Загрузка: сервисы подключаются, игрок ещё ничего не видит.</summary>
        Boot = 0,

        /// <summary>Главное меню.</summary>
        Menu = 1,

        /// <summary>Идёт игровая сессия (забег, раунд, уровень).</summary>
        Run = 2,

        /// <summary>Игровая сессия приостановлена одной или несколькими причинами паузы.</summary>
        Pause = 3,

        /// <summary>Сессия закончена, показан результат.</summary>
        Result = 4
    }
}
